async function seed() {
  console.log(`\n======================================================`);
  console.log(`🌱 RIVQ Curated Launch Seeder (15 Authentic Listings)`);
  console.log(`Target: ${supabaseUrl}`);
  console.log(`======================================================\n`);

  let inserted = 0;
  for (const item of CURATED_LISTINGS) {
    const { error } = await supabase.from("listings").upsert(item, { onConflict: "id" });
    if (error) {
      console.error(`  ✗ [Failed] ${item.id}:`, error.message);
    } else {
      console.log(`  ✓ [Inserted] [${item.event}] ${item.title} (${item.ownerCollege})`);
      inserted++;
    }
  }

  console.log(`\n✨ Seeding completed: ${inserted} / ${CURATED_LISTINGS.length} requisitions active.\n`);
}

seed().catch((err) => {
  console.error("Fatal seed error:", err);
  process.exit(1);
});
