async function seed() {
  console.log(`\n🚀 Starting database ingestion of survey dataset into Supabase (${supabaseUrl})...\n`);

  // 1. Ingest Users
  console.log("👤 Step 1: Ingesting Users...");
  for (const p of REAL_TALENT_PROFILES) {
    const userPayload = {
      id: p.user_id,
      name: p.display_name,
      email: p.email.toLowerCase().trim(),
      photo: p.photo,
      role: p.role,
      college: p.college,
      skills: p.skills,
      looking_for: p.looking_for.includes("hackathon") && p.looking_for.includes("research")
        ? "both"
        : p.looking_for.includes("hackathon")
        ? "hackathon"
        : "research",
      bio: p.bio,
      consent_at: p.created_at,
      created_at: p.created_at,
    };

    const { error } = await supabase.from("users").upsert(userPayload, { onConflict: "id" });
    if (error) {
      console.error(`  ✗ Error inserting user ${p.display_name}:`, error.message);
    } else {
      console.log(`  ✓ Inserted user: ${p.display_name} (${p.college})`);
    }
  }

  // 2. Ingest Talent Profiles
  console.log("\n🌟 Step 2: Ingesting Talent Profiles (/people)...");
  for (const p of REAL_TALENT_PROFILES) {
    const profilePayload = {
      id: p.id,
      user_id: p.user_id,
      display_name: p.display_name,
      email: p.email.toLowerCase().trim(),
      headline: p.headline,
      skills: p.skills,
      looking_for: p.looking_for,
      experience_level: p.experience_level,
      bio: p.bio,
      github: p.github,
      portfolio: p.portfolio,
      linkedin: p.linkedin,
      availability: p.availability,
      visible: p.visible,
      created_at: p.created_at,
    };

    const { error } = await supabase.from("talent_profiles").upsert(profilePayload, { onConflict: "id" });
    if (error) {
      console.error(`  ✗ Error inserting talent profile for ${p.display_name}:`, error.message);
    } else {
      console.log(`  ✓ Ingested profile: ${p.display_name} - ${p.headline}`);
    }
  }

  // 3. Ingest Listings
  console.log("\n📋 Step 3: Ingesting Requisitions / Listings (/)...");
  for (const l of REAL_LISTINGS) {
    const listingPayload = {
      id: l.id,
      owner_id: l.owner_id,
      owner_name: l.owner_name,
      owner_email: l.owner_email.toLowerCase().trim(),
      owner_college: l.owner_college,
      owner_role: l.owner_role,
      owner_photo: l.owner_photo,
      type: l.type,
      title: l.title,
      event: l.event,
      deadline: l.deadline,
      skills_needed: l.skills_needed,
      slots: l.slots,
      total_slots: l.total_slots,
      description: l.description,
      status: l.status,
      expires_at: l.expires_at,
      created_at: l.created_at,
    };

    const { error } = await supabase.from("listings").upsert(listingPayload, { onConflict: "id" });
    if (error) {
      console.error(`  ✗ Error inserting listing "${l.title}":`, error.message);
    } else {
      console.log(`  ✓ Ingested listing: [${l.event}] ${l.title}`);
    }
  }

  console.log("\n🎉 Database ingestion completed successfully!\n");
}

seed().catch((err) => {
  console.error("Fatal seed error:", err);
  process.exit(1);
});
